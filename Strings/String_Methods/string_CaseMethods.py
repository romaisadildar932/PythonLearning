#syntax -> string_name.method_name()
#lower method
name = "ROMAISA"
print(name.lower())

name1 = input("Enter your name: ")
print(name1.lower())

name2 = input("Enter your name: ").lower()
print(name2)

#upper method
print(name1.upper())

#capitalize method
print(name1.capitalize())

#title method
name3 = "my name is romaisa"
print(name3.title())

#swapcase method
name4 = "My Name Is Romaisa"
print(name4.swapcase())
